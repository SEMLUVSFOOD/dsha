# Generates source/core/ca_roots.c: the root certificates DSHA trusts for
# HTTPS, taken from Mozilla's CA store (curl's cacert.pem). Only a selection
# is embedded, enough for the certificates people use with Home Assistant
# (Let's Encrypt for Nabu Casa / DuckDNS / Tailscale, Google Trust Services
# for Cloudflare, ZeroSSL/Sectigo, the big commercial CAs).
#
# Usage:
#   curl -sfLo cacert.pem https://curl.se/ca/cacert.pem
#   python3 tools/gen_ca_roots.py cacert.pem > source/core/ca_roots.c
#
# With --check other.pem, every selected certificate must also be in
# other.pem (for example Debian's /etc/ssl/certs/ca-certificates.crt): a cross check
# against a second, independent source.

import hashlib
import re
import ssl
import sys

ROOTS = [
    "ISRG Root X1",                              # Let's Encrypt (RSA)
    "ISRG Root X2",                              # Let's Encrypt (ECDSA)
    "GTS Root R1",                               # Google Trust Services
    "GTS Root R3",
    "GTS Root R4",
    "USERTrust RSA Certification Authority",     # Sectigo, ZeroSSL
    "USERTrust ECC Certification Authority",
    "DigiCert Global Root G2",
    "DigiCert Global Root G3",
    "Amazon Root CA 1",
    "Amazon Root CA 3",
    "SSL.com TLS RSA Root CA 2022",
    "SSL.com TLS ECC Root CA 2022",
    "GlobalSign Root CA - R3",
    "GlobalSign Root R46",
    "GlobalSign Root E46",
    "Go Daddy Root Certificate Authority - G2",
    "Starfield Root Certificate Authority - G2",
    "Microsoft RSA Root Certificate Authority 2017",
]


def read_bundle(path):
    """Returns {label: der} for a curl style bundle (label line, '===', PEM)."""
    text = open(path, encoding="utf-8").read()
    certs = {}
    for m in re.finditer(r"(?m)^([^\n#][^\n]*)\n=+\n((?:#[^\n]*\n)*)"
                         r"(-----BEGIN CERTIFICATE-----.*?"
                         r"-----END CERTIFICATE-----)", text, re.S):
        der = ssl.PEM_cert_to_DER_cert(m.group(3))
        # The bundle lists the fingerprint of each certificate: check it
        fp = re.search(r"SHA-256\)?: ?([0-9A-F:]+)", m.group(2))
        if fp and fp.group(1).replace(":", "") != hashlib.sha256(der).hexdigest().upper():
            sys.exit(f"Fingerprint mismatch for {m.group(1)}")
        certs[m.group(1).strip()] = der
    return certs


def all_ders(path):
    text = open(path, encoding="utf-8").read()
    return {ssl.PEM_cert_to_DER_cert(m) for m in re.findall(
        r"-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----", text, re.S)}


def main():
    args = sys.argv[1:]
    check = None
    if "--check" in args:
        i = args.index("--check")
        check = all_ders(args[i + 1])
        del args[i:i + 2]
    bundle = read_bundle(args[0])
    date = ""
    m = re.search(r"Certificate data from Mozilla as of: ([^\n]+)",
                  open(args[0], encoding="utf-8").read())
    if m:
        date = m.group(1).strip()

    out = []
    out.append("// SPDX-License-Identifier: MPL-2.0\n//\n"
               "// Generated by tools/gen_ca_roots.py, don't edit. Root "
               "certificates from\n// Mozilla's CA store"
               + (f" ({date})" if date else "") + ", via "
               "https://curl.se/docs/caextract.html\n// (MPL-2.0, see "
               "licenses/ca-certificates.txt).\n\n"
               "#include \"ca_roots.h\"\n")
    names = []
    for i, name in enumerate(ROOTS):
        der = bundle.get(name)
        if der is None:
            sys.exit(f"{name} isn't in {args[0]}")
        if check is not None and der not in check:
            sys.exit(f"{name} isn't in the second bundle: check it")
        fp = hashlib.sha256(der).hexdigest().upper()
        out.append(f"\n// {name}\n// SHA-256 {fp}\n"
                   f"static const unsigned char root{i}[{len(der)}] = {{")
        for j in range(0, len(der), 12):
            out.append("    " + ", ".join(f"0x{b:02X}" for b in der[j:j + 12])
                       + ",")
        out.append("};\n")
        names.append(f"root{i}")
    out.append("const ca_root ca_roots[] = {")
    for n in names:
        out.append(f"    {{ {n}, sizeof({n}) }},")
    out.append("};\n")
    out.append("const int ca_roots_count = sizeof(ca_roots) / sizeof(ca_roots[0]);")
    print("\n".join(out))
    if check is not None:
        print(f"{len(names)} certificates, all found in the second bundle",
              file=sys.stderr)


if __name__ == "__main__":
    main()
